export type Labels = typeof DEFAULT_LABELS

/** Singular or plural label by count: plural(L, n, "rows") picks L.rowsOne when n is 1. */
export function plural<K extends keyof Labels>(L: Labels, n: number, many: K, one: keyof Labels): string {
	return n === 1 ? L[one] : L[many]
}

/** Fill "{name}" placeholders. Unknown placeholders stay as written. */
export function fill(template: string, vars: Record<string, string | number>): string {
	return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

