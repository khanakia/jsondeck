// Dev probe for the examples gallery, the bar-chart order and drawer JSON.
import { chromium } from "playwright"
const [base, mode = "http"] = process.argv.slice(2)
const b = await chromium.launch()
const out = []
const ok = (n, c, i = "") => out.push(`${c ? "PASS" : "FAIL"}  ${n}${i ? `  [${String(i).slice(0, 140)}]` : ""}`)
for (const scheme of ["light", "dark"]) {
	const ctx = await b.newContext({ viewport: { width: 1280, height: 1000 }, colorScheme: scheme, permissions: mode === "http" ? ["clipboard-read", "clipboard-write"] : [] })
	const p = await ctx.newPage()
	const errs = []
	p.on("pageerror", (e) => errs.push(String(e)))
	p.on("console", (m) => m.type() === "error" && errs.push(m.text()))
	await p.goto(`${base}/demo/examples.html`)
	await p.waitForTimeout(1200)
	if (scheme === "light") {
		const n = await p.locator('[data-jd="codeview"]').count()
		ok("examples: Preview/Code boxes render", n === 15, n)
		ok("nav has Examples link", (await p.locator("nav a", { hasText: "Examples" }).count()) > 0)
		const ex = p.locator("#ex-columns")
		ok("preview shows the table", (await ex.locator("tbody tr").count()) > 0)
		await ex.locator('[data-jd-codetab="code"]').click()
		const code = await ex.locator('[data-jd="code"]').textContent()
		ok("code tab: highlighted complete HTML (collapsed)", (await ex.locator('[data-jd="code"] span[class]').count()) > 20 && code.startsWith("<!doctype html>") && (await ex.locator('[data-jd="code-toggle"]').count()) === 1, code.split("\n").length + " lines shown")
		await ex.locator('[data-jd="code-toggle"]').click()
		const full = await ex.locator('[data-jd="code"]').textContent()
		ok("show all expands; snippet has CDN tags, data and mount", full.includes("cdn.jsdelivr.net/npm/jsondeck@0.1.0/dist/jsondeck.js") && full.includes('id="data"') && full.includes("JsonDeck.mount('#app'") && full.includes("pin: 'left'"), full.split("\n").length + " lines")
		const ov = await ex.locator('[data-jd="code"]').evaluate((el) => [getComputedStyle(el).overflowX, getComputedStyle(el).whiteSpace].join(" "))
		ok("code: no wrap, scrolls inside", ov === "auto pre", ov)
		await ex.locator('[data-jd="copy-code"]').click()
		await p.waitForTimeout(150)
		const state = await ex.locator('[data-jd="copy-code"]').getAttribute("data-jd-copied")
		let clip = ""
		if (mode === "http") clip = await p.evaluate(() => navigator.clipboard.readText()).catch((e) => `ERR ${e}`)
		ok(`copy (${mode}) reports Copied only when it worked`, state === "ok" && (mode !== "http" || clip === full.replace(/\n$/, "") + "\n" || clip.startsWith("<!doctype")), `${state} ${clip.slice(0, 30)}`)
		// computed example code shows functions as source
		await p.locator("#ex-computed").locator('[data-jd-codetab="code"]').click()
		await p.locator("#ex-computed").locator('[data-jd="code-toggle"]').click().catch(() => {})
		const c2 = await p.locator("#ex-computed").locator('[data-jd="code"]').textContent()
		ok("functions shown as source", c2.includes("value: (row) =>"), c2.match(/value:[^\n]*/)?.[0])
		ok("typed example: code only", (await p.locator('#ex-typed [data-jd-codetab="preview"]').count()) === 0 && (await p.locator("#ex-typed").textContent()).includes("defineConfig"))
		ok("errors example shows the issues box", (await p.locator('#ex-errors [data-jd="issues"]').count()) === 1)
		ok("chart examples render", (await p.locator("[data-jd-chart]").count()) >= 8, await p.locator("[data-jd-chart]").count())
		await p.locator("#ex-columns").locator('[data-jd-codetab="preview"]').click()
	}
	await p.screenshot({ path: `shots/examples-${mode}-${scheme}.png`, fullPage: false })
	await p.locator("#ex-bars").scrollIntoViewIfNeeded()
	await p.screenshot({ path: `shots/examples-${mode}-${scheme}-charts.png` })
	ok(`no console errors (${scheme})`, errs.length === 0, errs.join(" | "))
	await ctx.close()
}
// dashboard: bar order + drawer JSON + no issues box
const ctx = await b.newContext({ viewport: { width: 1400, height: 1000 } })
const p = await ctx.newPage()
await p.goto(`${base}/demo/index.html#/overview`)
await p.waitForTimeout(800)
const bars = await p.locator('[data-jd-chart="bar"] [aria-label]').evaluateAll((els) => els.map((e) => e.getAttribute("aria-label")))
ok("dashboard bar chart in severity order", bars.join(",") === "critical,high,medium,low", bars.join(","))
ok("dashboard has no issues box", (await p.locator('[data-jd="issues"]').count()) === 0)
await p.locator('[data-jd-item="sev-chart"]').screenshot({ path: `shots/dashboard-${mode}-bar.png` })
await p.locator('[data-jd-page-link="inventory"]').click()
await p.waitForTimeout(300)
await p.locator('[data-jd-item="ec2-table"] tbody tr').first().locator("td").nth(1).click()
await p.waitForTimeout(200)
const pre = p.locator('[data-jd="drawer-json"]').first()
const fits = await pre.evaluate((el) => el.getBoundingClientRect().right <= document.querySelector('[data-jd="drawer"]').getBoundingClientRect().right + 1)
ok("drawer JSON wraps inside the drawer", (await pre.count()) === 1 && fits)
await p.screenshot({ path: `shots/dashboard-${mode}-drawer.png` })
await b.close()
console.log(out.join("\n"))
